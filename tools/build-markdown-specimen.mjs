// Writes components/specimen/markdown-excerpts.mdx: every markdown element the
// posts use, as whole line ranges copied verbatim from published posts. The
// dev-only page pages/dev/markdown.js renders it for the paper type tools.
//   node tools/build-markdown-specimen.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const excerpts = [
  ['machine-code-isnt-scary', 13, 31],          // paragraphs, blockquote, h3, h2, ordered list
  ['overly-humble-programmer', 25, 25],          // strong
  ['learn-codebase-visualizer', 131, 131],       // emphasis
  ['learn-codebase-visualizer', 241, 241],       // strong, link, inline code
  ['never-change', 9, 11],                       // blockquote with attribution
  ['discovery-coding', 25, 28],                  // aside
  ['machine-code-isnt-scary', 97, 107],          // rust code block
  ['easiest-way-to-build-type-checker', 23, 37], // inline terms, link, typescript code block
  ['learn-codebase-visualizer', 31, 52],         // h3, inline code, bash code block
  ['learn-codebase-visualizer', 63, 63],         // image
  ['machine-code-isnt-scary', 350, 369],         // h2, plain code block, table
  ['ugliest-beautiful-codebase', 90, 90],        // note
  ['learn-codebase-visualizer', 380, 398],       // animation, h2, h4, rule, footnote
];

const out = [
  '{/* Generated by tools/build-markdown-specimen.mjs from published posts, copying',
  '    whole line ranges verbatim. Do not edit by hand. */}',
  'import { Term, Image, Aside, Note, Attribution } from "../../utils.mjs";',
  '',
];
for (const [name, first, last] of excerpts) {
  const lines = readFileSync(`pages/${name}.mdx`, 'utf8').split('\n');
  if (last > lines.length) throw new Error(`pages/${name}.mdx has ${lines.length} lines; excerpt asks for ${first}-${last}`);
  out.push(`{/* pages/${name}.mdx:${first}-${last} */}`, '', ...lines.slice(first - 1, last), '');
}
writeFileSync('components/specimen/markdown-excerpts.mdx', out.join('\n'));
